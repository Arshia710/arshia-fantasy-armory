// ---- where model and thumbnail files live ---------------------------------------
// data/paths.json is generated by build_paths.py. RUN IT after adding, moving or renaming any model
// (.bbmodel) or thumbnail. It maps a file NAME (without extension) to its path, so folders can be
// organised freely (weapons/majestica/x.bbmodel, armors/witcher/y.png, ...) and neither
// database.json, the scanner nor this code has to know about them:
//   { "models": { "abominableblade": "weapons/majestica/abominableblade.bbmodel", ... },
//     "thumbs": { "abominableblade": "weapons/majestica/abominableblade.png", ... } }
// Name lookup for an item (same rule as build_paths.py):
//   models: Full Set -> item id (malenia_full_set); others -> thumbnail name, model name, item id
//   thumbs: thumbnail name, model name, item id
// If paths.json cannot be loaded the old behaviour is used as a fallback.
const MODELS_DIR = "models";
const THUMBS_DIR = "thumbs";
let PATHS = null;
let SHARED_STEMS = new Set(); // in-game model names used by more than one item (e.g. two "mjolnir")

const lastPart = (s) => String(s || "").split("/").pop();

function computeSharedStems() {
  const count = {};
  for (const it of items) if (it.type !== "Full Set") count[lastPart(it.model)] = (count[lastPart(it.model)] || 0) + 1;
  SHARED_STEMS = new Set(Object.keys(count).filter((k) => count[k] > 1));
}

function lookupKeys(item, kind) {
  if (kind === "models" && item.type === "Full Set") return [item.id];
  const thumbStem = lastPart(item.thumbnail).replace(/\.[^.]+$/, "");
  let modelStem = lastPart(item.model);
  if (SHARED_STEMS.has(modelStem)) modelStem = ""; // ambiguous: only thumbnail name / id may identify the item
  return [...new Set([thumbStem, modelStem, item.id].filter(Boolean))];
}

function lookup(item, kind) {
  if (!PATHS) return null;
  for (const key of lookupKeys(item, kind)) if (PATHS[kind] && PATHS[kind][key]) return PATHS[kind][key];
  return null;
}

function thumbUrl(item) {
  const p = lookup(item, "thumbs");
  if (p) return `${THUMBS_DIR}/${p}`;
  return PATHS ? null : item.thumbnail || null; // paths.json missing -> old flat path from the database
}

function modelUrls(item) {
  const urls = [];
  const rel = (p) =>
    /^(https?:)?\/\//.test(p) || p.startsWith("/") || p.startsWith(MODELS_DIR + "/") ? p : `${MODELS_DIR}/${p}`;
  if (item.bbmodel) urls.push(rel(item.bbmodel)); // optional manual override in database.json
  const p = lookup(item, "models");
  if (p) urls.push(`${MODELS_DIR}/${p}`);
  else if (!PATHS && item.model) {
    // fallback without paths.json: models/<model path without namespace and leading "item/">.bbmodel
    urls.push(`${MODELS_DIR}/${item.model.replace(/^[^:]*:/, "").replace(/^item\//, "").toLowerCase()}.bbmodel`);
  }
  return [...new Set(urls)];
}

